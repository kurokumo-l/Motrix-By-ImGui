std::string_view Translator::Tr(std::string_view key) const noexcept {
    for (const auto& entry : kEntries) {
        if (entry.key == key) {
            return locale_ == Locale::ZhCN ? entry.zhCn : entry.enUs;
        }
    }
    return key;
}

